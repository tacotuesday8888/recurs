import console from "node:console";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { RECURS_BRAND } from "./recurs-brand.mjs";

const rootDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const GENERATED_HEADER = "Generated by scripts/generate-recurs-brand.mjs. Do not edit.";

function typescriptSource() {
  return `// ${GENERATED_HEADER}\n\nexport const RECURS_OPENING_WORDMARK_ROWS = Object.freeze(${JSON.stringify(RECURS_BRAND.openingWordmarkRows)});\n\nexport const RECURS_TERMINAL_ROWS = Object.freeze(${JSON.stringify(RECURS_BRAND.terminalRows)});\n\nexport const RECURS_TERMINAL_WORDMARK_ROWS = Object.freeze(${JSON.stringify(RECURS_BRAND.terminalWordmarkRows)});\n\nexport const RECURS_MARK_ANSI_256 = Object.freeze(${JSON.stringify(RECURS_BRAND.terminalAnsi256)});\n`;
}

// A block R echoes the terminal's extruded letter; warm colors match its default theme.
function markPaths() {
  return `<path d="M42 34h51c31 0 31 53 0 53H66v39H42zm24 20v14h25c9 0 9-14 0-14zm17 33h27l27 39h-29z" fill="url(#recurs-gradient)"/>`;
}
function gradient(width = 160, height = 160) {
  const { palette } = RECURS_BRAND;
  return `<linearGradient id="recurs-gradient" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="${width}" y2="${height}"><stop stop-color="${palette.highlight}"/><stop offset=".5" stop-color="${palette.orange}"/><stop offset="1" stop-color="${palette.ember}"/></linearGradient>`;
}
function markSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" role="img" aria-labelledby="title description">
<title id="title">Recurs</title><desc id="description">A warm orange block R, matching the terminal opening.</desc>
<!-- ${GENERATED_HEADER} -->
<defs>${gradient()}</defs>${markPaths()}
</svg>\n`;
}
function wordmarkSvg() {
  const { palette } = RECURS_BRAND;
  const glyphs = { "█": [[0,0,8,16]], "▀": [[0,0,8,8]], "▄": [[0,8,8,8]] };
  const pixels = RECURS_BRAND.openingWordmarkRows.flatMap((row, y) => Array.from(row).flatMap((ch, x) =>
    (glyphs[ch] ?? []).map(([dx,dy,w,h]) => `<rect x="${x*8+dx}" y="${y*16+dy}" width="${w}" height="${h}"/>`))).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 216" role="img" aria-labelledby="title description">
<title id="title">Recurs — one task, a team you control</title><desc id="description">The terminal's pixel wordmark in warm orange on charcoal.</desc>
<!-- ${GENERATED_HEADER} -->
<rect width="720" height="216" rx="16" fill="${palette.background}"/>
<defs>${gradient(184, 48)}</defs>
<g transform="translate(130 46) scale(2.5)" fill="url(#recurs-gradient)">${pixels}</g>
</svg>\n`;
}

const outputs = new Map([
  ["packages/cli/src/generated/recurs-brand.ts", typescriptSource()],
  ["docs/assets/recurs-mark.svg", markSvg()],
  ["docs/assets/recurs-wordmark.svg", wordmarkSvg()],
]);

let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(rootDirectory, relativePath);
  if (check) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== content) {
      console.error(`${relativePath} is stale; run npm run generate:recurs-brand`);
      stale = true;
    }
    continue;
  }
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, "utf8");
}

if (stale) process.exitCode = 1;
